//! Clipboard snapshots and the rules that decide what is worth recording.
//!
//! A [`ClipSnapshot`] is everything on the pasteboard at one moment: a list of
//! items, each a list of typed byte representations. Nothing here touches
//! AppKit; the app reads the pasteboard and hands the bytes to these
//! functions, which pick the one thing to show ([`summarize`]), cut a snapshot
//! down to that when it is too big ([`fit`]) and fingerprint it
//! ([`snapshot_hash`]).

use percent_encoding::percent_decode;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

/// Pasteboard type of a file reference.
pub const TYPE_FILE_URL: &str = "public.file-url";
/// Pasteboard type of UTF-8 plain text.
pub const TYPE_TEXT: &str = "public.utf8-plain-text";
/// Pasteboard type of a URL.
pub const TYPE_URL: &str = "public.url";
/// Pasteboard type of PNG image data.
pub const TYPE_PNG: &str = "public.png";
/// Pasteboard type of TIFF image data.
pub const TYPE_TIFF: &str = "public.tiff";

/// Types that mark a copy as secret, transient or machine-made: any item
/// carrying one keeps the whole copy out of the history.
pub const SECRET_MARKERS: [&str; 4] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// Largest snapshot, in bytes of data, that is stored whole.
pub const MAX_SNAPSHOT_BYTES: usize = 20 * 1024 * 1024;

/// Longest text preview, in characters.
const MAX_PREVIEW_CHARS: usize = 200;

/// One typed representation of a pasteboard item.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ClipRep {
    /// Pasteboard type name (a UTI such as `public.png`).
    pub ty: String,
    /// The raw bytes under that type.
    pub data: Vec<u8>,
}

/// Everything on the pasteboard at one moment.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ClipSnapshot {
    /// The pasteboard items, each with all its representations.
    pub items: Vec<Vec<ClipRep>>,
}

/// The one thing a snapshot is shown as in the list.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Summary {
    /// Copied files or folders.
    Files {
        /// Where they were when copied.
        paths: Vec<PathBuf>,
    },
    /// Copied text.
    Text {
        /// First non-blank line, trimmed, at most 200 characters.
        preview: String,
    },
    /// A copied link (never a `file:` URL).
    Link {
        /// The URL as copied.
        url: String,
    },
    /// A copied image.
    Image {
        /// `png` or `tiff`.
        ext: String,
        /// Width in pixels, 0 when it could not be read.
        width: u32,
        /// Height in pixels, 0 when it could not be read.
        height: u32,
    },
}

/// What a [`Summary`] was drawn from, so [`fit`] can keep exactly that.
enum Source {
    /// Every file-URL representation.
    Files,
    /// The representation at this index in the first item.
    Rep(usize),
}

/// Whether the copy carries a marker type and so must not be recorded.
pub fn is_secret(types: &[String]) -> bool {
    types.iter().any(|t| SECRET_MARKERS.contains(&t.as_str()))
}

/// Picks what the snapshot is shown as: files, then non-blank text, then a
/// non-`file:` URL, then a PNG, then a TIFF. `None` when it has none of them.
pub fn summarize(s: &ClipSnapshot) -> Option<Summary> {
    pick(s).map(|(summary, _)| summary)
}

/// Cuts `s` to what its summary was drawn from when it is bigger than
/// `limit` bytes of data, and `None` when even that does not fit (or there is
/// no summary to keep). A snapshot within the limit is returned unchanged.
pub fn fit(s: ClipSnapshot, limit: usize) -> Option<ClipSnapshot> {
    if size(&s) <= limit {
        return Some(s);
    }
    let (_, source) = pick(&s)?;
    let items = match source {
        Source::Files => s
            .items
            .into_iter()
            .map(|item| {
                item.into_iter()
                    .filter(|r| r.ty == TYPE_FILE_URL)
                    .collect::<Vec<_>>()
            })
            .filter(|item| !item.is_empty())
            .collect(),
        Source::Rep(i) => {
            let first = s.items.into_iter().next()?;
            vec![first.into_iter().nth(i).into_iter().collect()]
        }
    };
    let cut = ClipSnapshot { items };
    (size(&cut) <= limit).then_some(cut)
}

/// A 64-bit FNV-1a fingerprint of the whole snapshot (item order, type names
/// and bytes), used to tell a new copy from the one already recorded.
pub fn snapshot_hash(s: &ClipSnapshot) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325_u64;
    let mut feed = |bytes: &[u8]| {
        for &b in bytes {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    };
    for (i, item) in s.items.iter().enumerate() {
        feed(&(i as u64).to_le_bytes());
        for rep in item {
            feed(rep.ty.as_bytes());
            feed(&[0]);
            feed(&(rep.data.len() as u64).to_le_bytes());
            feed(&rep.data);
        }
    }
    h
}

/// The first item's plain text, decoded lossily.
pub fn plain_text(s: &ClipSnapshot) -> Option<String> {
    let rep = find(s.items.first()?, TYPE_TEXT)?;
    Some(String::from_utf8_lossy(&rep.data).into_owned())
}

/// The first item's image bytes and file extension, PNG before TIFF.
pub fn image(s: &ClipSnapshot) -> Option<(Vec<u8>, &'static str)> {
    let item = s.items.first()?;
    [(TYPE_PNG, "png"), (TYPE_TIFF, "tiff")]
        .into_iter()
        .find_map(|(ty, ext)| Some((find(item, ty)?.data.clone(), ext)))
}

/// Turns a `file://` or `file://localhost` URL into a path, percent-decoding
/// it. `None` for any other scheme, a relative path or bytes that are not
/// UTF-8.
pub fn file_url_to_path(url: &[u8]) -> Option<PathBuf> {
    let rest = url.strip_prefix(b"file://")?;
    let rest = rest.strip_prefix(b"localhost").unwrap_or(rest);
    if !rest.starts_with(b"/") {
        return None;
    }
    let path = percent_decode(rest).decode_utf8().ok()?;
    Some(PathBuf::from(path.into_owned()))
}

/// Extensions of the picture files a file copy is shown as a picture for.
const PICTURE_EXTS: [&str; 10] = [
    "png", "jpg", "jpeg", "gif", "heic", "heif", "tif", "tiff", "webp", "bmp",
];

/// For a copy of picture files only (a photo copied in Finder), the first
/// of them, so the copy can be shown as the picture it is; `None` for any
/// other summary.
pub fn shown_picture(summary: &Summary) -> Option<&Path> {
    let Summary::Files { paths } = summary else {
        return None;
    };
    let is_picture = |p: &PathBuf| {
        p.extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| PICTURE_EXTS.contains(&e.to_ascii_lowercase().as_str()))
    };
    paths
        .iter()
        .all(is_picture)
        .then(|| paths.first().map(PathBuf::as_path))
        .flatten()
}

/// Whether `path` is a file reference (`/.file/id=…`), the form Finder's
/// file reference URLs decode to; only the system can tell which file it is.
pub fn is_file_reference(path: &Path) -> bool {
    path.to_str().is_some_and(|p| p.starts_with("/.file/id="))
}

/// Removes the items whose file URL points at something `exists` denies (or
/// cannot be decoded). Items without a file URL stay.
pub fn drop_missing_files(s: ClipSnapshot, exists: impl Fn(&Path) -> bool) -> ClipSnapshot {
    let items = s
        .items
        .into_iter()
        .filter(|item| {
            item.iter()
                .filter(|r| r.ty == TYPE_FILE_URL)
                .all(|r| file_url_to_path(&r.data).is_some_and(|p| exists(&p)))
        })
        .collect();
    ClipSnapshot { items }
}

/// The summary together with the representations it came from.
fn pick(s: &ClipSnapshot) -> Option<(Summary, Source)> {
    let paths: Vec<PathBuf> = s
        .items
        .iter()
        .flatten()
        .filter(|r| r.ty == TYPE_FILE_URL)
        .filter_map(|r| file_url_to_path(&r.data))
        .collect();
    if !paths.is_empty() {
        return Some((Summary::Files { paths }, Source::Files));
    }

    let item = s.items.first()?;
    let at = |ty: &str| item.iter().position(|r| r.ty == ty);

    if let Some(i) = at(TYPE_TEXT)
        && let Some(preview) = preview(&item[i].data)
    {
        return Some((Summary::Text { preview }, Source::Rep(i)));
    }
    if let Some(i) = at(TYPE_URL) {
        let url = String::from_utf8_lossy(&item[i].data).trim().to_string();
        if !url.is_empty() && !url.to_ascii_lowercase().starts_with("file:") {
            return Some((Summary::Link { url }, Source::Rep(i)));
        }
    }
    for (ty, ext) in [(TYPE_PNG, "png"), (TYPE_TIFF, "tiff")] {
        if let Some(i) = at(ty) {
            let (width, height) = imagesize::blob_size(&item[i].data)
                .map_or((0, 0), |d| (d.width as u32, d.height as u32));
            let image = Summary::Image {
                ext: ext.into(),
                width,
                height,
            };
            return Some((image, Source::Rep(i)));
        }
    }
    None
}

/// First non-blank line of `data`, trimmed and capped; `None` if all blank.
fn preview(data: &[u8]) -> Option<String> {
    let text = String::from_utf8_lossy(data);
    let line = text
        .split(['\n', '\r', '\u{2028}'])
        .map(str::trim)
        .find(|l| !l.is_empty())?;
    Some(line.chars().take(MAX_PREVIEW_CHARS).collect())
}

/// The first representation of type `ty` in `item`.
fn find<'a>(item: &'a [ClipRep], ty: &str) -> Option<&'a ClipRep> {
    item.iter().find(|r| r.ty == ty)
}

/// Total bytes of data in the snapshot.
fn size(s: &ClipSnapshot) -> usize {
    s.items.iter().flatten().map(|r| r.data.len()).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rep(ty: &str, data: &[u8]) -> ClipRep {
        ClipRep {
            ty: ty.into(),
            data: data.to_vec(),
        }
    }

    fn snap(items: Vec<Vec<ClipRep>>) -> ClipSnapshot {
        ClipSnapshot { items }
    }

    /// Smallest byte string `imagesize` accepts as a PNG: signature plus IHDR.
    fn png(width: u32, height: u32) -> Vec<u8> {
        let mut b = vec![0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a];
        b.extend_from_slice(&13u32.to_be_bytes());
        b.extend_from_slice(b"IHDR");
        b.extend_from_slice(&width.to_be_bytes());
        b.extend_from_slice(&height.to_be_bytes());
        b.extend_from_slice(&[8, 6, 0, 0, 0]);
        b.extend_from_slice(&[0, 0, 0, 0]);
        b
    }

    #[test]
    fn secret_markers_on_any_item_skip() {
        let t = |s: &str| s.to_string();
        assert!(is_secret(&[
            t("public.utf8-plain-text"),
            t("org.nspasteboard.ConcealedType")
        ]));
        for m in SECRET_MARKERS {
            assert!(is_secret(&[t(m)]), "{m}");
        }
        assert!(!is_secret(&[t("public.utf8-plain-text")]));
    }

    #[test]
    fn files_beat_everything() {
        let s = snap(vec![
            vec![
                rep(TYPE_FILE_URL, b"file:///tmp/a%20b.txt"),
                rep(TYPE_TEXT, b"a b.txt"),
            ],
            vec![rep(TYPE_FILE_URL, b"file:///tmp/c.txt")],
        ]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Files {
                paths: vec!["/tmp/a b.txt".into(), "/tmp/c.txt".into()]
            })
        );
    }

    #[test]
    fn text_beats_image_in_summary() {
        let s = snap(vec![vec![
            rep(TYPE_PNG, &png(3, 2)),
            rep(TYPE_TEXT, b"A1\tB1"),
        ]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Text {
                preview: "A1\tB1".into()
            })
        );
    }

    #[test]
    fn blank_text_falls_through() {
        let s = snap(vec![vec![
            rep(TYPE_TEXT, b"  \n "),
            rep(TYPE_URL, b"https://x.y/"),
        ]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Link {
                url: "https://x.y/".into()
            })
        );
        assert_eq!(summarize(&snap(vec![vec![rep(TYPE_TEXT, b"  \n ")]])), None);
    }

    #[test]
    fn file_url_is_not_a_link() {
        let s = snap(vec![vec![rep(TYPE_URL, b"file:///tmp/x")]]);
        assert_eq!(summarize(&s), None);
    }

    #[test]
    fn image_summary_reads_size() {
        let s = snap(vec![vec![rep(TYPE_PNG, &png(3, 2))]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Image {
                ext: "png".into(),
                width: 3,
                height: 2
            })
        );
    }

    #[test]
    fn preview_is_first_nonblank_line_capped() {
        let s = snap(vec![vec![rep(TYPE_TEXT, b"\n  hello world  \nsecond")]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Text {
                preview: "hello world".into()
            })
        );
        // A lone CR (classic Mac text) and U+2028 end a line too.
        for text in ["one\rtwo", "one\u{2028}two", "one\r\ntwo"] {
            let s = snap(vec![vec![rep(TYPE_TEXT, text.as_bytes())]]);
            assert_eq!(
                summarize(&s),
                Some(Summary::Text {
                    preview: "one".into()
                }),
                "{text:?}"
            );
        }
        let long = "x".repeat(300);
        let s = snap(vec![vec![rep(TYPE_TEXT, long.as_bytes())]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Text {
                preview: "x".repeat(200)
            })
        );
    }

    #[test]
    fn fit_cuts_to_summary_then_skips() {
        let s = snap(vec![vec![
            rep(TYPE_TEXT, &[b'a'; 10]),
            rep("com.microsoft.Object-Descriptor", &[0; 100]),
        ]]);
        let cut = snap(vec![vec![rep(TYPE_TEXT, &[b'a'; 10])]]);
        assert_eq!(fit(s.clone(), 50), Some(cut));
        assert_eq!(fit(s.clone(), 5), None);
        assert_eq!(fit(s.clone(), 1000), Some(s));
    }

    #[test]
    fn hash_is_stable_and_sensitive() {
        let base = || {
            snap(vec![
                vec![rep(TYPE_TEXT, b"hello"), rep(TYPE_URL, b"https://x.y/")],
                vec![rep(TYPE_TEXT, b"world")],
            ])
        };
        assert_eq!(snapshot_hash(&base()), 14_747_925_391_063_540_697);
        assert_eq!(snapshot_hash(&base()), snapshot_hash(&base()));

        let mut one_byte = base();
        one_byte.items[0][0].data[0] = b'j';
        let mut one_type = base();
        one_type.items[0][1].ty = "public.urk".into();
        let mut order = base();
        order.items.reverse();
        for other in [one_byte, one_type, order] {
            assert_ne!(snapshot_hash(&other), snapshot_hash(&base()));
        }
    }

    #[test]
    fn copied_picture_files_show_as_pictures() {
        let files = |ps: &[&str]| Summary::Files {
            paths: ps.iter().map(PathBuf::from).collect(),
        };
        let one = files(&["/d/Photo.JPG"]);
        assert_eq!(shown_picture(&one), Some(Path::new("/d/Photo.JPG")));
        let all = files(&["/d/a.png", "/d/b.heic", "/d/c.webp"]);
        assert_eq!(shown_picture(&all), Some(Path::new("/d/a.png")));
        // One file that is not a picture makes it a file copy.
        assert_eq!(shown_picture(&files(&["/d/a.png", "/d/notes.txt"])), None);
        assert_eq!(shown_picture(&files(&["/d/png"])), None);
        assert_eq!(shown_picture(&files(&[])), None);
        let text = Summary::Text {
            preview: "a.png".into(),
        };
        assert_eq!(shown_picture(&text), None);
    }

    #[test]
    fn file_url_decoding() {
        assert_eq!(
            file_url_to_path(b"file:///tmp/a%20b"),
            Some(PathBuf::from("/tmp/a b"))
        );
        assert_eq!(
            file_url_to_path(b"file://localhost/tmp/x"),
            Some(PathBuf::from("/tmp/x"))
        );
        assert_eq!(file_url_to_path(b"https://x"), None);
        assert_eq!(file_url_to_path(b"file:///tmp/%FF"), None);
    }

    #[test]
    fn drop_missing_files_keeps_survivors() {
        let s = snap(vec![
            vec![rep(TYPE_FILE_URL, b"file:///a")],
            vec![rep(TYPE_FILE_URL, b"file:///b")],
            vec![rep(TYPE_TEXT, b"hi")],
        ]);
        let kept = drop_missing_files(s, |p| p == Path::new("/b"));
        assert_eq!(
            kept,
            snap(vec![
                vec![rep(TYPE_FILE_URL, b"file:///b")],
                vec![rep(TYPE_TEXT, b"hi")],
            ])
        );
    }

    #[test]
    fn fit_keeps_only_file_urls_of_a_big_file_copy() {
        let s = snap(vec![
            vec![rep(TYPE_FILE_URL, b"file:///a"), rep(TYPE_PNG, &[0; 100])],
            vec![rep(TYPE_TEXT, &[b'x'; 100])],
            vec![rep(TYPE_FILE_URL, b"file:///b")],
        ]);
        let cut = snap(vec![
            vec![rep(TYPE_FILE_URL, b"file:///a")],
            vec![rep(TYPE_FILE_URL, b"file:///b")],
        ]);
        assert_eq!(fit(s, 50), Some(cut));
    }

    #[test]
    fn plain_text_and_image_read_the_first_item() {
        let s = snap(vec![
            vec![
                rep(TYPE_TIFF, b"tiff"),
                rep(TYPE_PNG, b"png"),
                rep(TYPE_TEXT, "h\u{e9}llo".as_bytes()),
            ],
            vec![rep(TYPE_TEXT, b"other")],
        ]);
        assert_eq!(plain_text(&s).as_deref(), Some("h\u{e9}llo"));
        assert_eq!(image(&s), Some((b"png".to_vec(), "png")));
        let tiff_only = snap(vec![vec![rep(TYPE_TIFF, b"tiff")]]);
        assert_eq!(image(&tiff_only), Some((b"tiff".to_vec(), "tiff")));
        assert_eq!(plain_text(&tiff_only), None);
        assert_eq!(image(&ClipSnapshot::default()), None);
    }

    #[test]
    fn unreadable_image_is_zero_by_zero() {
        let s = snap(vec![vec![rep(TYPE_TIFF, b"not an image")]]);
        assert_eq!(
            summarize(&s),
            Some(Summary::Image {
                ext: "tiff".into(),
                width: 0,
                height: 0
            })
        );
    }
}
